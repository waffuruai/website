#!/usr/bin/env node
/**
 * Writes `src/generated/blog-posts.ts`: one static `import()` per blog post
 * and locale (`src/content/blog/<slug>/page.mdx`, `page.<locale>.mdx`).
 *
 * Bundlers resolve literal import paths reliably; a template-literal import
 * over two wildcards (`${slug}/${file}.mdx`) does not survive Turbopack once
 * translations exist. Generating the list keeps the blog markdown-driven: add
 * a folder or a translation and the next dev or build run picks it up.
 *
 *   node scripts/build-blog-index.mjs
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const POST_FILE = /^page(?:\.([a-z]{2}))?\.mdx$/;

/** `{ slug: { locale: file } }` for every post folder under `dir`. */
export async function scanPosts(dir) {
  const posts = {};
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  for (const entry of entries.filter((e) => e.isDirectory())) {
    for (const file of (await readdir(join(dir, entry.name))).sort()) {
      const match = file.match(POST_FILE);
      if (!match) continue;
      (posts[entry.name] ??= {})[match[1] ?? 'en'] = file;
    }
  }
  return posts;
}

/** The TypeScript module text for a scan result. */
export function renderIndex(posts) {
  const lines = Object.keys(posts)
    .sort()
    .map((slug) => {
      const locales = Object.entries(posts[slug])
        .sort(([a], [z]) =>
          a === 'en' ? -1 : z === 'en' ? 1 : a.localeCompare(z),
        )
        .map(
          ([locale, file]) =>
            `    ${locale}: () => import('@/content/blog/${slug}/${file}'),`,
        );
      return `  '${slug}': {\n${locales.join('\n')}\n  },`;
    });
  return `// Generated by scripts/build-blog-index.mjs from src/content/blog. Do not edit.
// Modules are typed in src/lib/blog.ts (\`PostModule\`).
type Loader = () => Promise<unknown>;

export const postModules: Record<string, Partial<Record<string, Loader>>> = {
${lines.join('\n')}
};
`;
}

async function main() {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const posts = await scanPosts(join(root, 'src/content/blog'));
  await mkdir(join(root, 'src/generated'), { recursive: true });
  await writeFile(
    join(root, 'src/generated/blog-posts.ts'),
    renderIndex(posts),
  );
  console.log(`blog index: ${Object.keys(posts).length} posts`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
