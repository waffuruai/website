#!/usr/bin/env node
/**
 * Writes `src/generated/build-info.ts`: the site's version, as every Waffuru
 * binary and script reports it (ops `.agents/PM.md`): `package.json`'s
 * version, plus the short commit and its date stamped at build time. The
 * footer prints `v1.0.0 (ed4972a 2026-10-28)`.
 *
 * The date is the commit's, not the clock's, so rebuilding the same commit
 * gives the same page. Outside a git checkout both fall back to "dev".
 *
 *   node scripts/build-info.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Output of a git command run in `cwd`, or null when git can't answer. */
function git(cwd, args) {
  try {
    return execFileSync('git', args, {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return null;
  }
}

/** `{ version, commit, date }` for the checkout at `root`. */
export async function readBuildInfo(root) {
  const { version } = JSON.parse(
    await readFile(join(root, 'package.json'), 'utf8'),
  );
  return {
    version,
    commit: git(root, ['rev-parse', '--short=7', 'HEAD']) ?? 'dev',
    date: git(root, ['log', '-1', '--format=%cs']) ?? 'dev',
  };
}

/** The TypeScript module the footer imports. */
export function renderBuildInfo(info) {
  return `// Generated by scripts/build-info.mjs. Do not edit.
export const buildInfo = ${JSON.stringify(info, null, 2)} as const;
`;
}

async function main() {
  const root = fileURLToPath(new URL('..', import.meta.url));
  const info = await readBuildInfo(root);
  await mkdir(join(root, 'src/generated'), { recursive: true });
  await writeFile(
    join(root, 'src/generated/build-info.ts'),
    renderBuildInfo(info),
  );
  console.log(`build info: v${info.version} (${info.commit} ${info.date})`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
